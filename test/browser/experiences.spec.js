test('lineup adds, moves, persists and restores a shared team-specific link',async({page})=>{
  await setup(page)
  await page.goto('/?team=cubs&tab=lineup')
  await page.getByLabel('Legend',{exact:true}).selectOption({label:'Ernie Banks'})
  await page.getByLabel('Position',{exact:true}).selectOption('SS')
  await page.getByRole('button',{name:'Add legend'}).click()
  await page.getByLabel('Move Ernie Banks to position').selectOption('1B')
  await expect(page.locator('.lineup-slot').filter({has:page.locator('.lineup-slot-head strong',{hasText:'1B'})})).toContainText('Ernie Banks')
  await page.reload()
  await expect(page.getByLabel('Move Ernie Banks to position')).toHaveValue('1B')
  await page.evaluate(()=> { window.shared=''; navigator.clipboard.writeText=async text=>{window.shared=text} })
  await page.getByRole('button',{name:'Share lineup'}).click()
  const link=await page.evaluate(()=>window.shared)
  expect(link).toContain('team=cubs&tab=lineup#lineup=')
  await page.evaluate(()=>localStorage.clear())
  await page.goto(link)
  await expect(page.getByLabel('Move Ernie Banks to position')).toHaveValue('1B')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(390)
})
