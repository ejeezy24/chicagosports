import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
const fixture = name => JSON.parse(readFileSync(new URL(`../fixtures/${name}.json`, import.meta.url), 'utf8'))
const summary = fixture('live-mlb')
async function setup(page, { live = false, spoiler = false } = {}) {
  await page.setViewportSize({width:390,height:844})
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.clock.setFixedTime(new Date('2026-09-18T17:00:00Z'))
  if (spoiler) await page.addInitScript(() => localStorage.setItem('cs.fan.v1', JSON.stringify({spoiler:true})))
  let final = !live
  const data = () => {
    const result = structuredClone(summary)
    result.header.competitions[0].status.type = {state: final ? 'post':'in', completed:final, shortDetail:final ? 'Final':'Bottom 7th'}
    result.situation = { balls:2,strikes:1,outs:1,onFirst:true,onSecond:false,pitchCount:65 }
    return result
  }
  await page.route('**/espn/**', route => {
    const url = new URL(route.request().url())
    if (url.pathname.endsWith('/summary')) return route.fulfill({json:data()})
    if (url.pathname.endsWith('/news')) return route.fulfill({json:{articles:[
      {id:1,headline:'Sox story from ESPN',published:'2026-09-18T12:00:00Z',categories:[{type:'team',teamId:4,description:'Chicago White Sox'}],links:{web:{href:'https://www.espn.com/story/1'}}},
      {id:2,headline:'Unrelated club story',categories:[{type:'team',teamId:16}],links:{web:{href:'https://www.espn.com/story/2'}}},
    ]}})
    if (url.pathname.endsWith('/schedule') || url.pathname.endsWith('/scoreboard')) {
      const competition = {...data().header.competitions[0]}
      return route.fulfill({json:{season:{year:2026,type:2},events:[{id:'401816978',date:'2026-09-17T23:40:00Z',season:{year:2026,type:2},competitions:[competition]}]}})
    }
    return route.fulfill({json:{}})
  })
  await page.route('**/mlbstats/**',route=>route.fulfill({json:{dates:[]}}))
  await page.route('**/nhlweb/**',route=>route.fulfill({json:{games:[]}}))
  await page.route('**/api/**',route=>route.fulfill({json:{events:[]}}))
  return { finish:()=>{final=true} }
}
test('news filters by team, respects spoilers and opens original source links',async({page})=>{
  await setup(page,{spoiler:true})
  await page.goto('/?team=whitesox&season=2026&tab=news')
  await expect(page.getByText('Sox story from ESPN')).toHaveCount(0)
  await page.getByRole('button',{name:/Reveal news headlines/}).click()
  await expect(page.getByRole('link',{name:/Sox story/})).toHaveAttribute('href','https://www.espn.com/story/1')
  await expect(page.getByText('Unrelated club story')).toHaveCount(0)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(390)
})
